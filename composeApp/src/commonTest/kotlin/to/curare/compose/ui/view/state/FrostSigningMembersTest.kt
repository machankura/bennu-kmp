package to.curare.compose.ui.view.state

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull
import to.curare.compose.database.model.ChatRoom
import to.curare.compose.database.model.Participant
import to.curare.compose.database.model.Profile
import to.curare.compose.database.model.intermdiate.LocalChatRoom
import to.curare.compose.database.model.intermdiate.LocalParticipant

/**
 * Who the signing screen lists as able to answer a proposal.
 *
 * A room is not the set that can sign with its key. A member added after the
 * ceremony holds no share, and the proposal they receive is dropped before it
 * becomes a session on their device -- so they can neither sign nor refuse,
 * and a row for them names a door that cannot answer. The list is the
 * ceremony's share holders, with the room supplying names.
 */
class FrostSigningMembersTest {
    private val alice = "a".repeat(64)
    private val bob = "b".repeat(64)
    private val carol = "c".repeat(64)

    /** In the room, invited after the key was made, and holding no share of it. */
    private val newcomer = "d".repeat(64)

    private fun room(vararg members: String) = LocalChatRoom(
        chatRoom = ChatRoom(
            id = "11".repeat(32),
            userPublicKey = alice,
            subject = "#Ekklesia",
            description = null,
            mlsGroupState = null,
        ),
        localParticipants = members.map { publicKey ->
            LocalParticipant(
                participant = Participant(
                    participantPublicKey = publicKey,
                    chatRoomId = "11".repeat(32),
                    relayHint = null,
                ),
                profile = Profile(
                    publicKey = publicKey,
                    userName = publicKey.take(1).uppercase(),
                    nostrEventId = "e".repeat(64),
                ),
            )
        },
    )

    private fun List<LocalParticipant>.keys() = map { it.participant.participantPublicKey }

    @Test
    fun `a member who holds no share is not listed`() {
        val state = FrostSigningUIState.Loaded(
            localChatRoom = room(alice, bob, newcomer, carol),
            shareHolders = setOf(alice, bob, carol)
        )

        // The newcomer is in the room and not in the ceremony. The session is
        // not waiting on them and cannot be answered by them.
        assertEquals(listOf(alice, bob, carol), state.members.keys())
    }

    @Test
    fun `names come off the room in the room's order`() {
        val state = FrostSigningUIState.Loaded(
            localChatRoom = room(carol, alice, bob),
            shareHolders = setOf(alice, bob, carol)
        )

        assertEquals(listOf(carol, alice, bob), state.members.keys())
        assertEquals(listOf("C", "A", "B"), state.members.map { it.profile?.userName })
    }

    @Test
    fun `a share holder the room no longer holds still has a row`() {
        // They left the room after the ceremony. Their share did not leave with
        // them: the count still needs them, or needs to know they refused.
        val state = FrostSigningUIState.Loaded(
            localChatRoom = room(alice, bob),
            shareHolders = setOf(alice, bob, carol)
        )

        assertEquals(listOf(alice, bob, carol), state.members.keys())
        assertNull(state.members.last().profile)
    }

    @Test
    fun `a room that holds a member twice lists them once`() {
        // Participant rows are keyed on an autogenerated id, so a room can
        // carry the same person twice; the list is of people.
        val state = FrostSigningUIState.Loaded(
            localChatRoom = room(alice, bob, bob),
            shareHolders = setOf(alice, bob)
        )

        assertEquals(listOf(alice, bob), state.members.keys())
    }

    @Test
    fun `nobody is listed until the ceremony has been read`() {
        // The first emission has the room and not yet the session it names.
        // Falling back to the room here would flash the wrong list -- everybody
        // -- and then correct itself, which is worse than a moment of nobody.
        val state = FrostSigningUIState.Loaded(localChatRoom = room(alice, bob, newcomer))

        assertEquals(emptyList(), state.members)
    }
}
